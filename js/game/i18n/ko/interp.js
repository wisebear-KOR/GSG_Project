export const cannotLabel = (k) => {
  const [kind, why] = k.split(':');
  if (why === 'villages') return '대성당(마을이 모자라다)';
  return `${CANNOT_KIND[kind] ?? kind}(${CANNOT_WHY[k] ?? CANNOT_WHY[why] ?? CANNOT_WHY[kind] ?? ''})`;
};

